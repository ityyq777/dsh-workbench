function fmt(text, vars) {
  return String(text).replace(/\{(\w+)\}/g, function (all, key) {
    return vars && vars[key] !== undefined ? String(vars[key]) : all;
  });
}

function pick(lang) {
  return lang === "en" ? EN : ZH;
}

